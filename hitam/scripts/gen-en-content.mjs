// Generate catalog.en.ts + proof.en.ts from the translation workflow result.
// Usage: node scripts/gen-en-content.mjs <path-to-result.json>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inPath = process.argv[2];
if (!inPath) {
  console.error("Pass the result JSON path as arg 1");
  process.exit(1);
}

let raw = readFileSync(inPath, "utf8").trim();
const first = raw.indexOf("{");
const last = raw.lastIndexOf("}");
if (first > 0 || last < raw.length - 1) raw = raw.slice(first, last + 1);
const parsed = JSON.parse(raw);
const result = parsed.result ?? parsed;

const decode = (s) =>
  typeof s === "string"
    ? s
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&quot;/g, '"')
        .replace(/&#0?39;/g, "'")
        .replace(/&apos;/g, "'")
        .replace(/&nbsp;/g, " ")
    : s;
const deep = (v) =>
  typeof v === "string"
    ? decode(v)
    : Array.isArray(v)
      ? v.map(deep)
      : v && typeof v === "object"
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, deep(x)]))
        : v;

const clean = deep(result);

const contentEn = {};
for (const s of clean.services) contentEn[s.slug] = s.data;

writeFileSync(
  resolve(root, "src/lib/catalog.en.ts"),
  `// AUTO-GENERATED by scripts/gen-en-content.mjs — English service content.
import type { ServiceContent } from "./types";

type ServiceBody = Omit<
  ServiceContent,
  "slug" | "name" | "icon" | "accent" | "short"
>;

export const CONTENT_EN: Record<string, ServiceBody> = ${JSON.stringify(contentEn, null, 2)};
`,
);

writeFileSync(
  resolve(root, "src/lib/proof.en.ts"),
  `// AUTO-GENERATED by scripts/gen-en-content.mjs — English proof data.
import type { Testimonial, SocialProofEvent } from "./types";

export const TESTIMONIALS_EN: Testimonial[] = ${JSON.stringify(clean.proof.testimonials, null, 2)};

export const SOCIAL_PROOF_EN: SocialProofEvent[] = ${JSON.stringify(clean.proof.social_proof, null, 2)};
`,
);

console.log(
  `OK — EN services: ${clean.services.length}, testimonials: ${clean.proof.testimonials.length}, social_proof: ${clean.proof.social_proof.length}`,
);
